-- Keymaps are automatically loaded on the VeryLazy event
-- Default keymaps that are always set: https://github.com/LazyVim/LazyVim/blob/main/lua/lazyvim/config/keymaps.lua
-- Add any additional keymaps here
local map = vim.keymap.set
map("n", "<S-tab>", "<cmd>bprevious<cr>", { desc = "Prev Buffer" })
map("n", "<tab>", "<cmd>bnext<cr>", { desc = "Next Buffer" })
map("n", ";", ":", { desc = "enter command" })
map("n", "<leader>lg", function()
  Snacks.lazygit()
end, { desc = "Lazygit", remap = true })

local nvim_tmux_nav = require("nvim-tmux-navigation")

map("n", "<C-h>", nvim_tmux_nav.NvimTmuxNavigateLeft)
map("n", "<C-j>", nvim_tmux_nav.NvimTmuxNavigateDown)
map("n", "<C-k>", nvim_tmux_nav.NvimTmuxNavigateUp)
map("n", "<C-l>", nvim_tmux_nav.NvimTmuxNavigateRight)
map("n", "<C-\\>", nvim_tmux_nav.NvimTmuxNavigateLastActive)
map("n", "<C-Space>", nvim_tmux_nav.NvimTmuxNavigateNext)
map("n", "<A-j>", "<cmd>cnext<CR>", { desc = "quickfix next" })
map("n", "<A-k>", "<cmd>cprev<CR>", { desc = "quickfix previous" })

map("n", "<leader>x", function()
  Snacks.bufdelete()
end, { desc = "Delete Buffer" })

map("n", "<leader>t", "", { desc = "Telescope commands" })
map("n", "<leader>tf", "<cmd>Telescope find_files<cr>", { desc = "Find Files" })
map("n", "<leader>tc", "<cmd>Telescope live_grep<cr>", { desc = "Live Grep" })
map("n", "<leader>tb", "<cmd>Telescope buffers<cr>", { desc = "Find Buffers" })
map("n", "<leader>tH", "<cmd>Telescope help_tags<cr>", { desc = "Help Tags" })
map("n", "<leader>to", "<cmd>Telescope oldfiles<cr>", { desc = "Recent Files" })
map("n", "<leader>ts", "<cmd>Telescope grep_string<cr>", { desc = "Search Current Word" })
map("n", "<leader>tk", "<cmd>Telescope keymaps<cr>", { desc = "Keymaps" })
map("n", "<leader>tm", "<cmd>Telescope marks<cr>", { desc = "Marks" })
map("n", "<leader>tr", "<cmd>Telescope registers<cr>", { desc = "Registers" })
map("n", "<leader>tq", "<cmd>Telescope quickfix<cr>", { desc = "Quickfix List" })
map("n", "<leader>tl", "<cmd>Telescope loclist<cr>", { desc = "Location List" })
map("n", "<leader>ta", "<cmd>Telescope autocommands<cr>", { desc = "Autocommands" })
map("n", "<leader>fi", "<cmd>Telescope current_buffer_fuzzy_find<cr>", { desc = "Fuzzy Find in Buffer" })
map("n", "<leader>tn", "<cmd>terminal<cr>", { desc = "Open a new terminal" })

map("n", "<leader>T", "", { desc = "Manage Tabs" })
map("n", "<leader>Tc", "<cmd>tabnew<cr>", { desc = "Create a new tab" })
map("n", "<leader>Td", "<cmd>tabclose<cr>", { desc = "Close tab" })
map("n", "<leader>Tn", "<cmd>tabnext<cr>", { desc = "Next tab" })
map("n", "<leader>Tp", "<cmd>tabprevious<cr>", { desc = "Previous Tab" })
map("t", "<esc><esc>", "<c-\\><c-n>", { desc = "exit terminal mode" })
map("t", "<leader><esc>", "<c-\\><c-n>", { desc = "exit terminal mode" })

map("n", "<leader>e", "", { desc = "Testing commands" })
map("n", "<leader>et", function()
  require("neotest").run.run(vim.fn.expand("%"))
end, { desc = "Run File (Neotest)" })
map("n", "<leader>eT", function()
  require("neotest").run.run(vim.uv.cwd())
end, { desc = "Run All Test Files (Neotest)" })
map("n", "<leader>er", function()
  require("neotest").run.run()
end, { desc = "Run Nearest (Neotest)" })
map("n", "<leader>el", function()
  require("neotest").run.run_last()
end, { desc = "Run Last (Neotest)" })
map("n", "<leader>es", function()
  require("neotest").summary.toggle()
end, { desc = "Toggle Summary (Neotest)" })
map("n", "<leader>eo", function()
  require("neotest").output.open({ enter = true, auto_close = true })
end, { desc = "Show Output (Neotest)" })
map("n", "<leader>eO", function()
  require("neotest").output_panel.toggle()
end, { desc = "Toggle Output Panel (Neotest)" })
map("n", "<leader>eS", function()
  require("neotest").run.stop()
end, { desc = "Stop (Neotest)" })
map("n", "<leader>ew", function()
  require("neotest").watch.toggle(vim.fn.expand("%"))
end, { desc = "Toggle Watch (Neotest)" })
map("n", "<leader>ed", function()
  require("neotest").run.run({ strategy = "dap" })
end, { desc = "Debug Nearest" })

map("n", "<leader>tf", LazyVim.pick("files", { cwd = ".", root = false }), { desc = "Find file", remap = true })
map("n", "<leader>th", function()
  require("telescope.builtin").colorscheme({
    enable_preview = true,
  })
end, { desc = "Select Colorscheme" })

vim.keymap.del("n", "<leader>/")
map("n", "<leader>/", "gcc", { remap = true })
map("v", "<leader>/", "gc", { remap = true })

vim.keymap.set("n", "<leader>o", "<cmd>Portal jumplist backward<cr>")
vim.keymap.set("n", "<leader>i", "<cmd>Portal jumplist forward<cr>")

local function blend(a, b, t)
   local function ch(hex, i)
      return tonumber(hex:sub(i, i + 1), 16)
   end
   local out = "#"
   for _, i in ipairs({ 2, 4, 6 }) do
      out = out .. ("%02x"):format(math.floor(ch(a, i) * (1 - t) + ch(b, i) * t + 0.5))
   end
   return out
end

